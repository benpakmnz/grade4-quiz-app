import { numberToHebrew, formatNumber } from './hebrewNumbers';

test.each([
  [0, 'אפס'],
  [7, 'שבע'],
  [12, 'שתים עשרה'],
  [20, 'עשרים'],
  [25, 'עשרים וחמש'],
  [100, 'מאה'],
  [105, 'מאה וחמש'],
  [120, 'מאה ועשרים'],
  [200, 'מאתיים'],
  [325, 'שלוש מאות עשרים וחמש'],
  [1000, 'אלף'],
  [1005, 'אלף וחמש'],
  [1300, 'אלף ושלוש מאות'],
  [1325, 'אלף שלוש מאות עשרים וחמש'],
  [2000, 'אלפיים'],
  [4000, 'ארבעת אלפים'],
  [10000, 'עשרת אלפים'],
  [10010, 'עשרת אלפים ועשר'],
  [11000, 'אחד עשר אלף'],
  [12000, 'שנים עשר אלף'],
  [21000, 'עשרים ואחד אלף'],
  [22000, 'עשרים ושניים אלף'],
  [45600, 'ארבעים וחמישה אלף ושש מאות'],
  [100000, 'מאה אלף'],
  [200000, 'מאתיים אלף'],
  [320500, 'שלוש מאות ועשרים אלף וחמש מאות'],
  [345678, 'שלוש מאות ארבעים וחמישה אלף שש מאות שבעים ושמונה'],
  [999999, 'תשע מאות תשעים ותשעה אלף תשע מאות תשעים ותשע'],
  [1000000, 'מיליון']
])('%i ← %s', (n, words) => {
  expect(numberToHebrew(n)).toBe(words);
});

test('rejects numbers outside the school range', () => {
  expect(() => numberToHebrew(-1)).toThrow();
  expect(() => numberToHebrew(1000001)).toThrow();
  expect(() => numberToHebrew(2.5)).toThrow();
});

test('thousands separators', () => {
  expect(formatNumber(345678)).toBe('345,678');
  expect(formatNumber(1000000)).toBe('1,000,000');
  expect(formatNumber(999)).toBe('999');
});

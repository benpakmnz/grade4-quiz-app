/**
 * מפרק פסקה למילים: { text, tag, punct, idx }.
 * tag = null למילה בלי סימון (בפסקאות שלא מסומנות במלואן)
 */
export const parseParagraph = (raw) =>
  raw.split(/\s+/).filter(Boolean).map((tok, idx) => {
    const m = /^([^|]+)\|([cnvapo])([.,!?:;"״'\-–]*)$/.exec(tok);
    if (m) return { text: m[1], tag: m[2], punct: m[3], idx };
    const p = /^(.*?)([.,!?:;"״\-–]*)$/.exec(tok);
    return { text: p[1], tag: null, punct: p[2], idx };
  });

/** כל הקטע כפסקאות של מילים */
export const parsePassage = (passage) => passage.paragraphs.map(parseParagraph);

/** הסבר קצר כשלוחצים על מילה שאינה מהסוג המבוקש */
export const wrongTapHint = (token, type) => {
  if (token.tag && TAG_NAMES[token.tag]) return `"${token.text}" - ${TAG_NAMES[token.tag]}, לא ${TAG_NAMES[type]}.`;
  if (type === 'c' && /^ו/.test(token.text) && token.text.length > 2) {
    return `ב"${token.text}" יש ו' החיבור - אבל כאן מחפשים מילת קישור שעומדת בפני עצמה (כמו אבל, כי, לכן).`;
  }
  return `"${token.text}" - לא ${TAG_NAMES[type]}. מחפשים ${TAG_SOME[type]}.`;
};
